USE WAREHOUSE DEFAULT_WH;
USE DATABASE HACKATHON_D2K_PREWORK;

-- Fingerprint of a snapshot's clone tables (row count + HASH_AGG per table).
CREATE OR REPLACE PROCEDURE L2P.SNAPSHOT_FINGERPRINT(SNAPSHOT_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  p VARCHAR;
  q VARCHAR;
  fp VARCHAR;
  rs RESULTSET;
BEGIN
  IF (NOT REGEXP_LIKE(:SNAPSHOT_ID, '^S[0-9]{5}$')) THEN RETURN NULL; END IF;
  p := 'HACKATHON_D2K_PREWORK.L2P_STAGE.SNAP_' || :SNAPSHOT_ID || '_';
  q := 'SELECT SHA2(CONCAT_WS(''|'','
    || '(SELECT COUNT(*)||'':''||HASH_AGG(*) FROM ' || p || 'INVOICES),'
    || '(SELECT COUNT(*)||'':''||HASH_AGG(*) FROM ' || p || 'INVOICELINES),'
    || '(SELECT COUNT(*)||'':''||HASH_AGG(*) FROM ' || p || 'CUSTOMERS),'
    || '(SELECT COUNT(*)||'':''||HASH_AGG(*) FROM ' || p || 'STOCKITEMS),'
    || '(SELECT COUNT(*)||'':''||HASH_AGG(*) FROM ' || p || 'STOCKITEMSTOCKGROUPS),'
    || '(SELECT COUNT(*)||'':''||HASH_AGG(*) FROM ' || p || 'ORDERS)), 256) AS FP';
  rs := (EXECUTE IMMEDIATE :q);
  LET c CURSOR FOR rs;
  FOR r IN c DO fp := r.FP; END FOR;
  RETURN fp;
END;
$$;

-- Immutable-by-procedure source snapshot: zero-copy clones of RAW plus recorded fingerprint.
CREATE OR REPLACE PROCEDURE L2P.TAKE_SNAPSHOT()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  sid VARCHAR;
  p VARCHAR;
  qids ARRAY DEFAULT ARRAY_CONSTRUCT();
  fp VARCHAR;
  objs VARIANT;
BEGIN
  SELECT 'S' || LPAD(L2P.SEQ_SNAPSHOT.NEXTVAL::VARCHAR, 5, '0') INTO :sid;
  p := 'HACKATHON_D2K_PREWORK.L2P_STAGE.SNAP_' || :sid || '_';
  EXECUTE IMMEDIATE 'CREATE TABLE ' || p || 'INVOICES CLONE HACKATHON_D2K_PREWORK.RAW.INVOICES';             qids := ARRAY_APPEND(:qids, LAST_QUERY_ID());
  EXECUTE IMMEDIATE 'CREATE TABLE ' || p || 'INVOICELINES CLONE HACKATHON_D2K_PREWORK.RAW.INVOICELINES';     qids := ARRAY_APPEND(:qids, LAST_QUERY_ID());
  EXECUTE IMMEDIATE 'CREATE TABLE ' || p || 'CUSTOMERS CLONE HACKATHON_D2K_PREWORK.RAW.CUSTOMERS';           qids := ARRAY_APPEND(:qids, LAST_QUERY_ID());
  EXECUTE IMMEDIATE 'CREATE TABLE ' || p || 'STOCKITEMS CLONE HACKATHON_D2K_PREWORK.RAW.STOCKITEMS';         qids := ARRAY_APPEND(:qids, LAST_QUERY_ID());
  EXECUTE IMMEDIATE 'CREATE TABLE ' || p || 'STOCKITEMSTOCKGROUPS CLONE HACKATHON_D2K_PREWORK.RAW.STOCKITEMSTOCKGROUPS'; qids := ARRAY_APPEND(:qids, LAST_QUERY_ID());
  EXECUTE IMMEDIATE 'CREATE TABLE ' || p || 'ORDERS CLONE HACKATHON_D2K_PREWORK.RAW.ORDERS';                 qids := ARRAY_APPEND(:qids, LAST_QUERY_ID());
  CALL L2P.SNAPSHOT_FINGERPRINT(:sid) INTO :fp;
  objs := ARRAY_CONSTRUCT(p||'INVOICES', p||'INVOICELINES', p||'CUSTOMERS', p||'STOCKITEMS', p||'STOCKITEMSTOCKGROUPS', p||'ORDERS');
  INSERT INTO L2P.SNAPSHOTS SELECT :sid, CURRENT_TIMESTAMP(), :objs, :fp, :qids;
  RETURN sid;
END;
$$;

-- Tool: propose a candidate from a fixed recipe. Records source definitions with live hashes and evidence-checked mappings.
CREATE OR REPLACE PROCEDURE L2P.PROPOSE_CANDIDATE(RECIPE_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  cid VARCHAR;
  n NUMBER;
  defs VARIANT;
  maps VARIANT;
  tpl VARCHAR;
  out VARIANT;
BEGIN
  SELECT COUNT(*) INTO :n FROM L2P.RECIPES WHERE RECIPE_ID = :RECIPE_ID;
  IF (n <> 1) THEN
    INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), NULL, 'PROPOSE', 'REJECTED',
      OBJECT_CONSTRUCT('reason','unsupported recipe','input', LEFT(:RECIPE_ID, 100));
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'UNSUPPORTED_RECIPE',
      'supported_recipes', (SELECT ARRAY_AGG(RECIPE_ID) FROM L2P.RECIPES)));
  END IF;
  SELECT 'C' || LPAD(L2P.SEQ_CANDIDATE.NEXTVAL::VARCHAR, 5, '0') || '_' || UPPER(SUBSTR(REPLACE(UUID_STRING(), '-', ''), 1, 8)) INTO :cid;
  SELECT SQL_TEMPLATE INTO :tpl FROM L2P.RECIPES WHERE RECIPE_ID = :RECIPE_ID;
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT('doc_id', c.DOC_ID, 'title', c.TITLE, 'artifact_type', c.ARTIFACT_TYPE,
           'source_path', c.SOURCE_PATH, 'catalog_source_version', c.SOURCE_VERSION, 'catalog_content_sha256', SHA2(c.CONTENT, 256)))
    INTO :defs
    FROM HACKATHON_D2K_PREWORK.ANALYTICS.T_PREWORK_CATALOG c
    JOIN L2P.RECIPES r ON ARRAY_CONTAINS(c.DOC_ID::VARIANT, r.SOURCE_DOC_IDS)
   WHERE r.RECIPE_ID = :RECIPE_ID;
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT('target_field', m.TARGET_FIELD, 'source_expression', m.SOURCE_EXPRESSION,
           'evidence_doc_id', m.EVIDENCE_DOC_ID, 'evidence_path', c.SOURCE_PATH, 'evidence_version', c.SOURCE_VERSION,
           'evidence_text', m.EVIDENCE_TEXT, 'note', m.NOTE,
           'status', CASE WHEN m.EVIDENCE_DOC_ID IS NULL THEN 'MISSING_EVIDENCE'
                          WHEN c.DOC_ID IS NULL OR NOT CONTAINS(c.CONTENT, m.EVIDENCE_TEXT) THEN 'EVIDENCE_NOT_FOUND'
                          WHEN m.SOURCE_EXPRESSION IS NULL THEN 'SOURCE_BACKED_NOT_MODELED'
                          ELSE 'SOURCE_BACKED' END))
    INTO :maps
    FROM L2P.RECIPE_MAPPINGS m
    LEFT JOIN HACKATHON_D2K_PREWORK.ANALYTICS.T_PREWORK_CATALOG c ON c.DOC_ID = m.EVIDENCE_DOC_ID
   WHERE m.RECIPE_ID = 'DAILY_INVOICED_SALES_V1';
  INSERT INTO L2P.CANDIDATES (CANDIDATE_ID, RECIPE_ID, PRODUCT, CONTRACT_VERSION, STATE, SOURCE_DEFINITIONS, MAPPINGS, RENDERED_SQL, PROPOSED_AT, REQUESTED_BY)
    SELECT :cid, :RECIPE_ID, 'DAILY_INVOICED_SALES', 1, 'PROPOSED', :defs, :maps, :tpl, CURRENT_TIMESTAMP(), CURRENT_USER();
  INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :cid, 'PROPOSE', 'PROPOSED', OBJECT_CONSTRUCT('recipe', :RECIPE_ID);
  out := OBJECT_CONSTRUCT('ok', TRUE, 'candidate_id', :cid, 'state', 'PROPOSED', 'recipe_id', :RECIPE_ID,
           'contract_version', 1, 'source_definitions', :defs, 'mappings', :maps, 'sql_template', :tpl,
           'note', 'Proposal only. Nothing has been created. Call CREATE_CANDIDATE to build from a fresh source snapshot.');
  RETURN TO_JSON(out);
END;
$$;

-- Tool: create the candidate table from a fresh snapshot.
CREATE OR REPLACE PROCEDURE L2P.CREATE_CANDIDATE(CANDIDATE_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  sid VARCHAR;
  tpl VARCHAR;
  sqltext VARCHAR;
  obj VARCHAR;
  p VARCHAR;
  qid VARCHAR;
  h VARCHAR;
  n NUMBER;
  claimed NUMBER;
  err VARCHAR;
BEGIN
  IF (NOT REGEXP_LIKE(:CANDIDATE_ID, '^C[0-9]{5}_[0-9A-F]{8}$')) THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'INVALID_CANDIDATE_ID_FORMAT'));
  END IF;
  SELECT COUNT(*) INTO :n FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID;
  IF (n = 0) THEN RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'UNKNOWN_CANDIDATE', 'candidate_id', :CANDIDATE_ID)); END IF;
  CALL L2P.TAKE_SNAPSHOT() INTO :sid;
  -- Claim: only one caller can move a PROPOSED candidate to creation.
  UPDATE L2P.CANDIDATES SET SNAPSHOT_ID = :sid WHERE CANDIDATE_ID = :CANDIDATE_ID AND STATE = 'PROPOSED' AND SNAPSHOT_ID IS NULL;
  claimed := SQLROWCOUNT;
  IF (claimed <> 1) THEN
    INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'CREATE', 'REJECTED', OBJECT_CONSTRUCT('reason','not in PROPOSED state or already claimed','orphan_snapshot', :sid);
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'INVALID_STATE', 'candidate_id', :CANDIDATE_ID,
      'state', (SELECT STATE FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID)));
  END IF;
  SELECT r.SQL_TEMPLATE INTO :tpl FROM L2P.CANDIDATES c JOIN L2P.RECIPES r ON r.RECIPE_ID = c.RECIPE_ID WHERE c.CANDIDATE_ID = :CANDIDATE_ID;
  p := 'HACKATHON_D2K_PREWORK.L2P_STAGE.SNAP_' || :sid || '_';
  sqltext := REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(:tpl,
    '{{INVOICELINES}}', p||'INVOICELINES'), '{{INVOICES}}', p||'INVOICES'), '{{CUSTOMERS}}', p||'CUSTOMERS'),
    '{{STOCKITEMS}}', p||'STOCKITEMS'), '{{STOCKITEMSTOCKGROUPS}}', p||'STOCKITEMSTOCKGROUPS'), '{{ORDERS}}', p||'ORDERS');
  obj := 'HACKATHON_D2K_PREWORK.L2P_STAGE.CAND_' || :CANDIDATE_ID;
  BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE ' || :obj || ' AS ' || :sqltext;
    qid := LAST_QUERY_ID();
    LET rs RESULTSET := (EXECUTE IMMEDIATE 'SELECT COUNT(*) AS N, HASH_AGG(*)::VARCHAR AS H FROM ' || :obj);
    LET c CURSOR FOR rs;
    FOR r IN c DO n := r.N; h := r.H; END FOR;
  EXCEPTION WHEN OTHER THEN
    err := SQLERRM;
    UPDATE L2P.CANDIDATES SET STATE = 'FAILED', FAILED_AT = CURRENT_TIMESTAMP(), FAILURE_REASON = 'CREATE_ERROR: ' || :err, RENDERED_SQL = :sqltext
      WHERE CANDIDATE_ID = :CANDIDATE_ID;
    EXECUTE IMMEDIATE 'DROP TABLE IF EXISTS ' || :obj;
    INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'CREATE', 'FAILED', OBJECT_CONSTRUCT('error', :err);
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'CREATE_ERROR', 'detail', :err, 'state', 'FAILED'));
  END;
  UPDATE L2P.CANDIDATES SET STATE = 'CREATED', CREATED_AT = CURRENT_TIMESTAMP(), RENDERED_SQL = :sqltext, BUILD_QUERY_ID = :qid,
         CANDIDATE_OBJECT = :obj, CONTENT_HASH = :h, ROW_COUNT = :n
   WHERE CANDIDATE_ID = :CANDIDATE_ID AND STATE = 'PROPOSED';
  INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'CREATE', 'CREATED', OBJECT_CONSTRUCT('snapshot', :sid, 'query_id', :qid, 'rows', :n);
  RETURN TO_JSON(OBJECT_CONSTRUCT('ok', TRUE, 'candidate_id', :CANDIDATE_ID, 'state', 'CREATED', 'snapshot_id', :sid,
    'candidate_object', :obj, 'build_query_id', :qid, 'row_count', :n, 'content_hash', :h, 'executed_sql', :sqltext,
    'note', 'Created but NOT validated or released. Call VALIDATE_CANDIDATE.'));
END;
$$;

-- Run one check query (returning OBSERVED, EXPECTED, PASSED) and record it. Errors are recorded as ERROR.
CREATE OR REPLACE PROCEDURE L2P.RUN_CHECK(RUN_ID VARCHAR, CANDIDATE_ID VARCHAR, CHECK_NAME VARCHAR, CHECK_SQL VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  qid VARCHAR;
  st VARCHAR;
BEGIN
  EXECUTE IMMEDIATE 'INSERT INTO L2P.CHECK_RESULTS SELECT ''' || :RUN_ID || ''', ''' || :CANDIDATE_ID || ''', ''' || :CHECK_NAME
    || ''', IFF(PASSED, ''PASS'', ''FAIL''), TO_VARIANT(OBSERVED), TO_VARIANT(EXPECTED), NULL, CURRENT_TIMESTAMP() FROM (' || :CHECK_SQL || ')';
  qid := LAST_QUERY_ID();
  UPDATE L2P.CHECK_RESULTS SET QUERY_ID = :qid WHERE RUN_ID = :RUN_ID AND CHECK_NAME = :CHECK_NAME;
  SELECT MAX(STATUS) INTO :st FROM L2P.CHECK_RESULTS WHERE RUN_ID = :RUN_ID AND CHECK_NAME = :CHECK_NAME;
  RETURN st;
EXCEPTION WHEN OTHER THEN
  LET err VARCHAR := SQLERRM;
  INSERT INTO L2P.CHECK_RESULTS SELECT :RUN_ID, :CANDIDATE_ID, :CHECK_NAME, 'ERROR', TO_VARIANT(:err), NULL, NULL, CURRENT_TIMESTAMP();
  RETURN 'ERROR';
END;
$$;

-- Tool: validate a CREATED candidate against the contract, reconciling independently to its snapshot.
CREATE OR REPLACE PROCEDURE L2P.VALIDATE_CANDIDATE(CANDIDATE_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  run VARCHAR;
  sid VARCHAR;
  obj VARCHAR;
  tname VARCHAR;
  p VARCHAR;
  fp_rec VARCHAR;
  fp_now VARCHAR;
  h0 VARCHAR;
  h1 VARCHAR;
  n NUMBER;
  st VARCHAR;
  e VARCHAR;
  npass NUMBER;
  nfail NUMBER;
  final_state VARCHAR;
  failed ARRAY;
BEGIN
  IF (NOT REGEXP_LIKE(:CANDIDATE_ID, '^C[0-9]{5}_[0-9A-F]{8}$')) THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'INVALID_CANDIDATE_ID_FORMAT'));
  END IF;
  SELECT COUNT(*) INTO :n FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID;
  IF (n = 0) THEN RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'UNKNOWN_CANDIDATE', 'candidate_id', :CANDIDATE_ID)); END IF;
  SELECT 'V' || LPAD(L2P.SEQ_RUN.NEXTVAL::VARCHAR, 5, '0') INTO :run;
  UPDATE L2P.CANDIDATES SET LATEST_VALIDATION_RUN_ID = :run
   WHERE CANDIDATE_ID = :CANDIDATE_ID AND STATE = 'CREATED' AND LATEST_VALIDATION_RUN_ID IS NULL;
  IF (SQLROWCOUNT <> 1) THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'INVALID_STATE', 'candidate_id', :CANDIDATE_ID,
      'state', (SELECT STATE FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID),
      'note', 'Only a CREATED candidate that has not been validated can be validated. Propose a new candidate to retry.'));
  END IF;
  SELECT SNAPSHOT_ID, CANDIDATE_OBJECT INTO :sid, :obj FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID;
  SELECT FINGERPRINT INTO :fp_rec FROM L2P.SNAPSHOTS WHERE SNAPSHOT_ID = :sid;
  tname := 'CAND_' || :CANDIDATE_ID;
  p := 'HACKATHON_D2K_PREWORK.L2P_STAGE.SNAP_' || :sid || '_';
  LET rs0 RESULTSET := (EXECUTE IMMEDIATE 'SELECT HASH_AGG(*)::VARCHAR AS H FROM ' || :obj);
  LET c0 CURSOR FOR rs0;
  FOR r IN c0 DO h0 := r.H; END FOR;
  INSERT INTO L2P.VALIDATION_RUNS SELECT :run, :CANDIDATE_ID, :sid, CURRENT_TIMESTAMP(), NULL, :h0, NULL, 'RUNNING', 0, 0;

  -- Independent expectation: computed from snapshot lines/headers only, sums subtracted after aggregation.
  e := '(SELECT h.INVOICEDATE AS D, h.CUSTOMERID AS C, l.STOCKITEMID AS S, COUNT(*) AS N, SUM(l.QUANTITY) AS Q, '
    || 'SUM(l.EXTENDEDPRICE) - SUM(l.TAXAMOUNT) AS AMT, SUM(l.TAXAMOUNT) AS TAX, SUM(l.EXTENDEDPRICE) AS TOT '
    || 'FROM ' || p || 'INVOICELINES l, ' || p || 'INVOICES h WHERE h.INVOICEID = l.INVOICEID GROUP BY 1,2,3)';

  CALL L2P.SNAPSHOT_FINGERPRINT(:sid) INTO :fp_now;
  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'SNAPSHOT_UNCHANGED',
    'SELECT ''' || :fp_now || ''' AS OBSERVED, ''' || :fp_rec || ''' AS EXPECTED, ''' || :fp_now || ''' = ''' || :fp_rec || ''' AS PASSED');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'SCHEMA_EXACT',
    'SELECT OBJECT_CONSTRUCT(''mismatches'', ARRAY_AGG(IFF(OK, NULL, OBJECT_CONSTRUCT(''contract'', F, ''actual'', A, ''contract_type'', T, ''actual_type'', AT)))) AS OBSERVED, '
    || '''exact contract v1 fields and types'' AS EXPECTED, COUNT_IF(NOT OK) = 0 AS PASSED FROM ('
    || 'SELECT k.FIELD_NAME F, a.COLUMN_NAME A, k.DATA_TYPE || COALESCE(''(''||k.NUMERIC_PRECISION||'',''||k.NUMERIC_SCALE||'')'','''') T, '
    || 'a.DATA_TYPE || COALESCE(''(''||a.NUMERIC_PRECISION||'',''||a.NUMERIC_SCALE||'')'','''') AT, '
    || 'k.FIELD_NAME IS NOT NULL AND a.COLUMN_NAME IS NOT NULL AND k.DATA_TYPE = a.DATA_TYPE '
    || 'AND EQUAL_NULL(k.NUMERIC_PRECISION, a.NUMERIC_PRECISION) AND EQUAL_NULL(k.NUMERIC_SCALE, a.NUMERIC_SCALE) AS OK '
    || 'FROM (SELECT * FROM L2P.CONTRACT_FIELDS WHERE PRODUCT = ''DAILY_INVOICED_SALES'' AND CONTRACT_VERSION = 1) k '
    || 'FULL OUTER JOIN (SELECT COLUMN_NAME, DATA_TYPE, NUMERIC_PRECISION, NUMERIC_SCALE FROM HACKATHON_D2K_PREWORK.INFORMATION_SCHEMA.COLUMNS '
    || 'WHERE TABLE_SCHEMA = ''L2P_STAGE'' AND TABLE_NAME = ''' || :tname || ''') a ON a.COLUMN_NAME = k.FIELD_NAME)');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'KEYS_NOT_NULL',
    'SELECT COUNT_IF(INVOICE_DATE IS NULL OR CUSTOMER_ID IS NULL OR STOCK_ITEM_ID IS NULL) AS OBSERVED, 0 AS EXPECTED, OBSERVED = 0 AS PASSED FROM ' || :obj);

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'GRAIN_UNIQUE',
    'SELECT COUNT(*) - COUNT(DISTINCT INVOICE_DATE, CUSTOMER_ID, STOCK_ITEM_ID) AS OBSERVED, 0 AS EXPECTED, OBSERVED = 0 AS PASSED FROM ' || :obj);

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'REFERENTIAL_INTEGRITY',
    'SELECT OBJECT_CONSTRUCT(''orphan_customers'', (SELECT COUNT(*) FROM ' || :obj || ' x WHERE NOT EXISTS (SELECT 1 FROM ' || :p || 'CUSTOMERS c WHERE c.CUSTOMERID = x.CUSTOMER_ID)), '
    || '''orphan_items'', (SELECT COUNT(*) FROM ' || :obj || ' x WHERE NOT EXISTS (SELECT 1 FROM ' || :p || 'STOCKITEMS s WHERE s.STOCKITEMID = x.STOCK_ITEM_ID)), '
    || '''orphan_date_customer'', (SELECT COUNT(*) FROM ' || :obj || ' x WHERE NOT EXISTS (SELECT 1 FROM ' || :p || 'INVOICES h WHERE h.INVOICEDATE = x.INVOICE_DATE AND h.CUSTOMERID = x.CUSTOMER_ID)), '
    || '''orphan_lines_in_source'', (SELECT COUNT(*) FROM ' || :p || 'INVOICELINES l WHERE NOT EXISTS (SELECT 1 FROM ' || :p || 'INVOICES h WHERE h.INVOICEID = l.INVOICEID))) AS OBSERVED, '
    || '''all zero'' AS EXPECTED, OBSERVED:orphan_customers = 0 AND OBSERVED:orphan_items = 0 AND OBSERVED:orphan_date_customer = 0 AND OBSERVED:orphan_lines_in_source = 0 AS PASSED');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'LINE_COVERAGE',
    'SELECT OBJECT_CONSTRUCT(''candidate_lines'', cl, ''source_lines'', sl, ''dropped_lines'', GREATEST(sl - cl, 0), ''multiplied_lines'', GREATEST(cl - sl, 0)) AS OBSERVED, '
    || 'sl AS EXPECTED, cl = sl AS PASSED FROM (SELECT (SELECT SUM(INVOICE_LINE_COUNT) FROM ' || :obj || ') cl, (SELECT COUNT(*) FROM ' || :p || 'INVOICELINES) sl)');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'ROW_COUNT_MATCH',
    'SELECT (SELECT COUNT(*) FROM ' || :obj || ') AS OBSERVED, (SELECT COUNT(*) FROM ' || :e || ') AS EXPECTED, OBSERVED = EXPECTED AS PASSED');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'GROUPED_RECONCILIATION',
    'SELECT OBJECT_CONSTRUCT(''missing_in_candidate'', COUNT_IF(x.INVOICE_DATE IS NULL), ''extra_in_candidate'', COUNT_IF(e.D IS NULL), '
    || '''value_mismatches'', COUNT_IF(x.INVOICE_DATE IS NOT NULL AND e.D IS NOT NULL AND (x.INVOICE_LINE_COUNT <> e.N OR x.QUANTITY <> e.Q OR x.SALES_EXCLUDING_TAX <> e.AMT OR x.TAX_AMOUNT <> e.TAX OR x.TOTAL_INCLUDING_TAX <> e.TOT)), '
    || '''sample'', ARRAY_SLICE(ARRAY_AGG(IFF(x.INVOICE_DATE IS NULL OR e.D IS NULL OR x.SALES_EXCLUDING_TAX <> e.AMT OR x.INVOICE_LINE_COUNT <> e.N, '
    || 'OBJECT_CONSTRUCT(''date'', COALESCE(x.INVOICE_DATE, e.D), ''customer'', COALESCE(x.CUSTOMER_ID, e.C), ''item'', COALESCE(x.STOCK_ITEM_ID, e.S), ''cand_amt'', x.SALES_EXCLUDING_TAX, ''src_amt'', e.AMT, ''cand_lines'', x.INVOICE_LINE_COUNT, ''src_lines'', e.N), NULL)), 0, 5)) AS OBSERVED, '
    || '''0 missing, 0 extra, 0 value mismatches'' AS EXPECTED, '
    || 'OBSERVED:missing_in_candidate = 0 AND OBSERVED:extra_in_candidate = 0 AND OBSERVED:value_mismatches = 0 AS PASSED '
    || 'FROM ' || :obj || ' x FULL OUTER JOIN ' || :e || ' e ON e.D = x.INVOICE_DATE AND e.C = x.CUSTOMER_ID AND e.S = x.STOCK_ITEM_ID');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'TOTAL_RECONCILIATION',
    'SELECT OBJECT_CONSTRUCT(''sales_ex_tax'', a.s, ''tax'', a.t, ''total'', a.g) AS OBSERVED, OBJECT_CONSTRUCT(''sales_ex_tax'', b.s, ''tax'', b.t, ''total'', b.g) AS EXPECTED, '
    || 'a.s = b.s AND a.t = b.t AND a.g = b.g AS PASSED FROM '
    || '(SELECT SUM(SALES_EXCLUDING_TAX) s, SUM(TAX_AMOUNT) t, SUM(TOTAL_INCLUDING_TAX) g FROM ' || :obj || ') a, '
    || '(SELECT SUM(EXTENDEDPRICE - TAXAMOUNT) s, SUM(TAXAMOUNT) t, SUM(EXTENDEDPRICE) g FROM ' || :p || 'INVOICELINES) b');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'DIMENSION_CONSISTENCY',
    'SELECT COUNT_IF(NOT EQUAL_NULL(x.CUSTOMER_NAME, c.CUSTOMERNAME) OR NOT EQUAL_NULL(x.STOCK_ITEM_NAME, s.STOCKITEMNAME)) AS OBSERVED, 0 AS EXPECTED, OBSERVED = 0 AS PASSED '
    || 'FROM ' || :obj || ' x LEFT JOIN ' || :p || 'CUSTOMERS c ON c.CUSTOMERID = x.CUSTOMER_ID LEFT JOIN ' || :p || 'STOCKITEMS s ON s.STOCKITEMID = x.STOCK_ITEM_ID');

  CALL L2P.RUN_CHECK(:run, :CANDIDATE_ID, 'SCOPE_CONSISTENCY',
    'SELECT OBJECT_CONSTRUCT(''min_date'', a.mn, ''max_date'', a.mx, ''dates'', a.nd, ''customers'', a.nc, ''items'', a.ni) AS OBSERVED, '
    || 'OBJECT_CONSTRUCT(''min_date'', b.mn, ''max_date'', b.mx, ''dates'', b.nd, ''customers'', b.nc, ''items'', b.ni) AS EXPECTED, '
    || 'a.mn = b.mn AND a.mx = b.mx AND a.nd = b.nd AND a.nc = b.nc AND a.ni = b.ni AS PASSED FROM '
    || '(SELECT MIN(INVOICE_DATE) mn, MAX(INVOICE_DATE) mx, COUNT(DISTINCT INVOICE_DATE) nd, COUNT(DISTINCT CUSTOMER_ID) nc, COUNT(DISTINCT STOCK_ITEM_ID) ni FROM ' || :obj || ') a, '
    || '(SELECT MIN(D) mn, MAX(D) mx, COUNT(DISTINCT D) nd, COUNT(DISTINCT C) nc, COUNT(DISTINCT S) ni FROM ' || :e || ') b');

  LET rs1 RESULTSET := (EXECUTE IMMEDIATE 'SELECT HASH_AGG(*)::VARCHAR AS H FROM ' || :obj);
  LET c1 CURSOR FOR rs1;
  FOR r IN c1 DO h1 := r.H; END FOR;
  SELECT COUNT_IF(STATUS = 'PASS'), COUNT_IF(STATUS <> 'PASS'), ARRAY_AGG(IFF(STATUS <> 'PASS', CHECK_NAME, NULL))
    INTO :npass, :nfail, :failed FROM L2P.CHECK_RESULTS WHERE RUN_ID = :run;
  IF (nfail = 0 AND npass = 11 AND h0 = h1) THEN final_state := 'VALIDATED'; ELSE final_state := 'FAILED'; END IF;
  UPDATE L2P.VALIDATION_RUNS SET FINISHED_AT = CURRENT_TIMESTAMP(), CONTENT_HASH_END = :h1,
         OVERALL_STATUS = IFF(:final_state = 'VALIDATED', 'PASS', 'FAIL'), CHECKS_PASSED = :npass, CHECKS_FAILED = :nfail WHERE RUN_ID = :run;
  IF (final_state = 'VALIDATED') THEN
    UPDATE L2P.CANDIDATES SET STATE = 'VALIDATED', VALIDATED_AT = CURRENT_TIMESTAMP(), CONTENT_HASH = :h1
     WHERE CANDIDATE_ID = :CANDIDATE_ID AND STATE = 'CREATED' AND LATEST_VALIDATION_RUN_ID = :run;
  ELSE
    UPDATE L2P.CANDIDATES SET STATE = 'FAILED', FAILED_AT = CURRENT_TIMESTAMP(),
           FAILURE_REASON = 'VALIDATION_FAILED: ' || ARRAY_TO_STRING(:failed, ',') || IFF(:h0 = :h1, '', ' + CONTENT_CHANGED_DURING_VALIDATION')
     WHERE CANDIDATE_ID = :CANDIDATE_ID AND LATEST_VALIDATION_RUN_ID = :run;
  END IF;
  INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'VALIDATE', :final_state, OBJECT_CONSTRUCT('run', :run, 'failed_checks', :failed);
  RETURN TO_JSON(OBJECT_CONSTRUCT('ok', TRUE, 'candidate_id', :CANDIDATE_ID, 'validation_run_id', :run, 'state', :final_state,
    'checks_passed', :npass, 'checks_failed', :nfail, 'failed_checks', :failed,
    'checks', (SELECT ARRAY_AGG(OBJECT_CONSTRUCT('check', CHECK_NAME, 'status', STATUS, 'observed', OBSERVED, 'expected', EXPECTED, 'query_id', QUERY_ID))
                 FROM L2P.CHECK_RESULTS WHERE RUN_ID = :run),
    'note', IFF(:final_state = 'VALIDATED', 'Validated. Not yet released: call RELEASE_CANDIDATE.', 'Failed. This candidate can never be released.')));
EXCEPTION WHEN OTHER THEN
  -- Any crash leaves an explicit FAILED state, never a half-finished validation.
  LET verr VARCHAR := SQLERRM;
  UPDATE L2P.VALIDATION_RUNS SET FINISHED_AT = CURRENT_TIMESTAMP(), OVERALL_STATUS = 'ERROR' WHERE RUN_ID = :run;
  UPDATE L2P.CANDIDATES SET STATE = 'FAILED', FAILED_AT = CURRENT_TIMESTAMP(), FAILURE_REASON = 'VALIDATION_ERROR: ' || :verr
   WHERE CANDIDATE_ID = :CANDIDATE_ID AND LATEST_VALIDATION_RUN_ID = :run AND STATE = 'CREATED';
  INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'VALIDATE', 'ERROR', OBJECT_CONSTRUCT('error', :verr, 'run', :run);
  RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'VALIDATION_ERROR', 'detail', :verr, 'state', 'FAILED'));
END;
$$;

-- Tool: release. The only path that writes L2P_RELEASE and the current-release pointer.
CREATE OR REPLACE PROCEDURE L2P.RELEASE_CANDIDATE(CANDIDATE_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  n NUMBER;
  st VARCHAR;
  run VARCHAR;
  run_status VARCHAR;
  run_fail NUMBER;
  latest_run VARCHAR;
  vhash VARCHAR;
  obj VARCHAR;
  sid VARCHAR;
  fp_rec VARCHAR;
  fp_now VARCHAR;
  hnow VARCHAR;
  hrel VARCHAR;
  ver NUMBER;
  relobj VARCHAR;
  qid VARCHAR;
  rows_rel NUMBER;
  cur_ver NUMBER;
  err VARCHAR;
BEGIN
  IF (NOT REGEXP_LIKE(:CANDIDATE_ID, '^C[0-9]{5}_[0-9A-F]{8}$')) THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'INVALID_CANDIDATE_ID_FORMAT'));
  END IF;
  SELECT COUNT(*) INTO :n FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID;
  IF (n = 0) THEN RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'UNKNOWN_CANDIDATE', 'candidate_id', :CANDIDATE_ID)); END IF;
  SELECT STATE, LATEST_VALIDATION_RUN_ID, CONTENT_HASH, CANDIDATE_OBJECT, SNAPSHOT_ID, RELEASED_VERSION
    INTO :st, :run, :vhash, :obj, :sid, :cur_ver FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID;
  IF (st = 'RELEASED') THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'ALREADY_RELEASED', 'released_version', :cur_ver, 'note', 'No new version created.'));
  END IF;
  IF (st <> 'VALIDATED') THEN
    INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'RELEASE', 'REJECTED', OBJECT_CONSTRUCT('state', :st);
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'NOT_VALIDATED', 'state', :st,
      'current_release', (SELECT OBJECT_CONSTRUCT('version', VERSION, 'object', RELEASE_OBJECT) FROM L2P.RELEASES WHERE IS_CURRENT AND PRODUCT = 'DAILY_INVOICED_SALES')));
  END IF;
  -- Latest validation run must be this candidate's run, PASS, zero failures.
  SELECT MAX(RUN_ID) INTO :latest_run FROM L2P.VALIDATION_RUNS WHERE CANDIDATE_ID = :CANDIDATE_ID;
  SELECT OVERALL_STATUS, CHECKS_FAILED INTO :run_status, :run_fail FROM L2P.VALIDATION_RUNS WHERE RUN_ID = :run;
  IF (latest_run <> run OR run_status <> 'PASS' OR run_fail <> 0) THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'STALE_OR_FAILED_VALIDATION', 'run', :run, 'latest_run', :latest_run));
  END IF;
  -- Candidate content and snapshot must be unchanged since validation.
  LET rs RESULTSET := (EXECUTE IMMEDIATE 'SELECT HASH_AGG(*)::VARCHAR AS H FROM ' || :obj);
  LET c CURSOR FOR rs;
  FOR r IN c DO hnow := r.H; END FOR;
  SELECT FINGERPRINT INTO :fp_rec FROM L2P.SNAPSHOTS WHERE SNAPSHOT_ID = :sid;
  CALL L2P.SNAPSHOT_FINGERPRINT(:sid) INTO :fp_now;
  IF (NOT EQUAL_NULL(hnow, vhash) OR NOT EQUAL_NULL(fp_now, fp_rec)) THEN
    UPDATE L2P.CANDIDATES SET STATE = 'FAILED', FAILED_AT = CURRENT_TIMESTAMP(),
      FAILURE_REASON = 'CHANGED_AFTER_VALIDATION: candidate_hash ' || :vhash || ' -> ' || COALESCE(:hnow, 'NULL') || IFF(:fp_now = :fp_rec, '', '; snapshot changed')
     WHERE CANDIDATE_ID = :CANDIDATE_ID AND STATE = 'VALIDATED';
    INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'RELEASE', 'REJECTED_CHANGED', OBJECT_CONSTRUCT('validated_hash', :vhash, 'current_hash', :hnow);
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'CHANGED_AFTER_VALIDATION', 'validated_hash', :vhash, 'current_hash', :hnow, 'state', 'FAILED'));
  END IF;
  -- Clone to a unique versioned release object, then verify the clone itself.
  SELECT L2P.SEQ_RELEASE.NEXTVAL INTO :ver;
  relobj := 'HACKATHON_D2K_PREWORK.L2P_RELEASE.DAILY_INVOICED_SALES_V' || LPAD(:ver::VARCHAR, 4, '0');
  BEGIN
    EXECUTE IMMEDIATE 'CREATE TABLE ' || :relobj || ' CLONE ' || :obj;
    qid := LAST_QUERY_ID();
    LET rs2 RESULTSET := (EXECUTE IMMEDIATE 'SELECT HASH_AGG(*)::VARCHAR AS H, COUNT(*) AS N FROM ' || :relobj);
    LET c2 CURSOR FOR rs2;
    FOR r IN c2 DO hrel := r.H; rows_rel := r.N; END FOR;
    IF (NOT EQUAL_NULL(hrel, vhash)) THEN
      EXECUTE IMMEDIATE 'DROP TABLE IF EXISTS ' || :relobj;
      RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'RELEASE_CLONE_HASH_MISMATCH'));
    END IF;
    -- Atomic registry switch: conditional state change + pointer move in one transaction.
    BEGIN TRANSACTION;
    UPDATE L2P.CANDIDATES SET STATE = 'RELEASED', RELEASED_AT = CURRENT_TIMESTAMP(), RELEASED_VERSION = :ver
     WHERE CANDIDATE_ID = :CANDIDATE_ID AND STATE = 'VALIDATED' AND CONTENT_HASH = :vhash AND LATEST_VALIDATION_RUN_ID = :run;
    IF (SQLROWCOUNT <> 1) THEN
      ROLLBACK;
      EXECUTE IMMEDIATE 'DROP TABLE IF EXISTS ' || :relobj;
      RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'CONCURRENT_STATE_CHANGE', 'note', 'Another request changed this candidate; nothing released.'));
    END IF;
    UPDATE L2P.RELEASES SET IS_CURRENT = FALSE, SUPERSEDED_AT = CURRENT_TIMESTAMP() WHERE PRODUCT = 'DAILY_INVOICED_SALES' AND IS_CURRENT;
    INSERT INTO L2P.RELEASES SELECT :ver, 'DAILY_INVOICED_SALES', :CANDIDATE_ID, :relobj, :hrel, :rows_rel, :sid, :run, CURRENT_TIMESTAMP(), TRUE, NULL, :qid;
    INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'RELEASE', 'RELEASED', OBJECT_CONSTRUCT('version', :ver, 'object', :relobj);
    COMMIT;
  EXCEPTION WHEN OTHER THEN
    err := SQLERRM;
    ROLLBACK;
    EXECUTE IMMEDIATE 'DROP TABLE IF EXISTS ' || :relobj;
    INSERT INTO L2P.EVENT_LOG SELECT L2P.SEQ_EVENT.NEXTVAL, CURRENT_TIMESTAMP(), :CANDIDATE_ID, 'RELEASE', 'ERROR', OBJECT_CONSTRUCT('error', :err);
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'RELEASE_ERROR', 'detail', :err, 'note', 'Previous release unchanged.'));
  END;
  RETURN TO_JSON(OBJECT_CONSTRUCT('ok', TRUE, 'candidate_id', :CANDIDATE_ID, 'state', 'RELEASED', 'released_version', :ver,
    'release_object', :relobj, 'content_hash', :hrel, 'row_count', :rows_rel, 'validation_run_id', :run, 'snapshot_id', :sid, 'clone_query_id', :qid));
END;
$$;

-- Tool: read-only registry status for one candidate (or recent candidates when NULL/empty).
CREATE OR REPLACE PROCEDURE L2P.GET_CANDIDATE_STATUS(CANDIDATE_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  IF (COALESCE(:CANDIDATE_ID, '') = '') THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT(
      'candidates', (SELECT ARRAY_AGG(OBJECT_CONSTRUCT('candidate_id', CANDIDATE_ID, 'recipe', RECIPE_ID, 'state', STATE, 'released_version', RELEASED_VERSION, 'failure_reason', FAILURE_REASON)) WITHIN GROUP (ORDER BY CANDIDATE_ID DESC) FROM L2P.CANDIDATES),
      'current_release', (SELECT OBJECT_CONSTRUCT('version', VERSION, 'object', RELEASE_OBJECT, 'candidate_id', CANDIDATE_ID) FROM L2P.RELEASES WHERE IS_CURRENT)));
  END IF;
  IF (NOT EXISTS (SELECT 1 FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID)) THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'UNKNOWN_CANDIDATE', 'candidate_id', LEFT(:CANDIDATE_ID, 40)));
  END IF;
  RETURN (SELECT TO_JSON(OBJECT_CONSTRUCT('ok', TRUE, 'candidate_id', CANDIDATE_ID, 'recipe', RECIPE_ID, 'state', STATE, 'snapshot_id', SNAPSHOT_ID,
            'candidate_object', CANDIDATE_OBJECT, 'build_query_id', BUILD_QUERY_ID, 'content_hash', CONTENT_HASH, 'row_count', ROW_COUNT,
            'validation_run_id', LATEST_VALIDATION_RUN_ID, 'released_version', RELEASED_VERSION, 'failure_reason', FAILURE_REASON,
            'proposed_at', PROPOSED_AT, 'created_at', CREATED_AT, 'validated_at', VALIDATED_AT, 'failed_at', FAILED_AT, 'released_at', RELEASED_AT))
          FROM L2P.CANDIDATES WHERE CANDIDATE_ID = :CANDIDATE_ID);
END;
$$;

-- Tool: exact catalog document retrieval by DOC_ID or SOURCE_PATH (read-only, catalog table only).
CREATE OR REPLACE PROCEDURE L2P.GET_SOURCE_DEFINITION(DOC_ID_OR_PATH VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM HACKATHON_D2K_PREWORK.ANALYTICS.T_PREWORK_CATALOG WHERE DOC_ID = :DOC_ID_OR_PATH OR SOURCE_PATH = :DOC_ID_OR_PATH)) THEN
    RETURN TO_JSON(OBJECT_CONSTRUCT('ok', FALSE, 'error', 'NOT_IN_CATALOG', 'input', LEFT(:DOC_ID_OR_PATH, 200),
      'note', 'Absence from this catalog does not prove the object does not exist elsewhere.'));
  END IF;
  RETURN (SELECT TO_JSON(OBJECT_CONSTRUCT('ok', TRUE, 'documents', ARRAY_AGG(OBJECT_CONSTRUCT('doc_id', DOC_ID, 'title', TITLE, 'artifact_type', ARTIFACT_TYPE,
            'source_path', SOURCE_PATH, 'source_version', SOURCE_VERSION, 'content_sha256', SHA2(CONTENT, 256), 'content', CONTENT))))
          FROM HACKATHON_D2K_PREWORK.ANALYTICS.T_PREWORK_CATALOG WHERE DOC_ID = :DOC_ID_OR_PATH OR SOURCE_PATH = :DOC_ID_OR_PATH);
END;
$$;

-- Tool: ordered vs invoiced reconciliation (fixed read-only SQL over RAW).
CREATE OR REPLACE PROCEDURE L2P.RECONCILE_ORDERED_VS_INVOICED()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  RETURN (SELECT TO_JSON(OBJECT_CONSTRUCT(
    'orders', (SELECT COUNT(*) FROM HACKATHON_D2K_PREWORK.RAW.ORDERS),
    'orders_with_invoice', (SELECT COUNT(DISTINCT o.ORDERID) FROM HACKATHON_D2K_PREWORK.RAW.ORDERS o JOIN HACKATHON_D2K_PREWORK.RAW.INVOICES i ON i.ORDERID = o.ORDERID),
    'orders_without_invoice_in_snapshot', (SELECT COUNT(*) FROM HACKATHON_D2K_PREWORK.RAW.ORDERS o WHERE NOT EXISTS (SELECT 1 FROM HACKATHON_D2K_PREWORK.RAW.INVOICES i WHERE i.ORDERID = o.ORDERID)),
    'ordered_value_ex_tax_all_orders', (SELECT SUM(ROUND(QUANTITY * UNITPRICE, 2)) FROM HACKATHON_D2K_PREWORK.RAW.ORDERLINES),
    'ordered_value_ex_tax_invoiced_orders', (SELECT SUM(ROUND(l.QUANTITY * l.UNITPRICE, 2)) FROM HACKATHON_D2K_PREWORK.RAW.ORDERLINES l WHERE EXISTS (SELECT 1 FROM HACKATHON_D2K_PREWORK.RAW.INVOICES i WHERE i.ORDERID = l.ORDERID)),
    'ordered_value_ex_tax_uninvoiced_orders', (SELECT SUM(ROUND(l.QUANTITY * l.UNITPRICE, 2)) FROM HACKATHON_D2K_PREWORK.RAW.ORDERLINES l WHERE NOT EXISTS (SELECT 1 FROM HACKATHON_D2K_PREWORK.RAW.INVOICES i WHERE i.ORDERID = l.ORDERID)),
    'invoiced_sales_ex_tax', (SELECT SUM(EXTENDEDPRICE - TAXAMOUNT) FROM HACKATHON_D2K_PREWORK.RAW.INVOICELINES),
    'invoices', (SELECT COUNT(*) FROM HACKATHON_D2K_PREWORK.RAW.INVOICES),
    'order_date_range', (SELECT MIN(ORDERDATE)||'..'||MAX(ORDERDATE) FROM HACKATHON_D2K_PREWORK.RAW.ORDERS),
    'invoice_date_range', (SELECT MIN(INVOICEDATE)||'..'||MAX(INVOICEDATE) FROM HACKATHON_D2K_PREWORK.RAW.INVOICES),
    'basis', 'Ordered = ROUND(ORDERLINES.QUANTITY*UNITPRICE,2) by ORDERDATE (Qlik Sales Performance). Invoiced = INVOICELINES.EXTENDEDPRICE-TAXAMOUNT by INVOICEDATE (Spotfire Customer Sales). Both exclude tax.',
    'query_id', LAST_QUERY_ID())));
END;
$$;
